// Run: node tests/browser.cjs (starts its own local HTTP server).
const { chromium, webkit } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const path = require('node:path'), fs = require('node:fs');
  const root = path.resolve(__dirname, '..');
  const server = require('node:http').createServer((req, res) => {
    const file = path.join(root, new URL(req.url, 'http://localhost').pathname.replace(/\/$/, '/index.html'));
    if (!file.startsWith(root + path.sep)) { res.writeHead(403).end(); return; }
    fs.readFile(file, (err, data) => {
      if (err) { res.writeHead(404).end(); return; }
      const types = { '.js': 'application/javascript', '.html': 'text/html', '.css': 'text/css', '.png': 'image/png', '.json': 'application/json' };
      res.setHeader('Content-Type', types[path.extname(file)] || 'text/plain'); res.end(data);
    });
  });
  await new Promise(resolve => server.listen(8000, '127.0.0.1', resolve));
  const engine = process.env.BROWSER === 'webkit' ? webkit : chromium;
  let browser;
  try { browser = await engine.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox', '--disable-dev-shm-usage', '--no-zygote'] } : {}) });
    const context = await browser.newContext({ viewport: { width: 393, height: 852 }, acceptDownloads: true });
    const page = await context.newPage();
    const eventually = async (read, check = Boolean) => { for (let n = 0; n < 100; n++) { if (check(await read())) return; await new Promise(resolve => setTimeout(resolve, 30)); } throw new Error('Expected persisted state was not reached'); };
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.route('**/seed', r => r.fulfill({ contentType: 'text/html', body: '<html></html>' }));
    await page.goto('http://127.0.0.1:8000/seed');
    await page.evaluate(() => new Promise((resolve, reject) => {
      const req = indexedDB.open('recipeDB', 2);
      req.onupgradeneeded = () => {
        const db = req.result;
        db.createObjectStore('recipes', { keyPath: 'id', autoIncrement: true }).add({ title: 'Старый борщ', ingredients: 'Мясо — 500 г\nСоль по вкусу', steps: 'Нарезать\nВарить', favorite: true, createdAt: 1 });
        const cats = db.createObjectStore('categories', { keyPath: 'name' });
        ['Супы', 'Другое'].forEach(name => cats.add({ name }));
      };
      req.onsuccess = () => { req.result.close(); resolve(); }; req.onerror = () => reject(req.error);
    }));
    await page.goto('http://127.0.0.1:8000/');
    await page.waitForFunction(() => document.querySelectorAll('.recipe-card').length === 1);
    assert.equal(await page.evaluate(() => db.version), 3);
    await page.locator('.recipe-card').click();
    await page.locator('#dEdit').waitFor();
    assert.match(await page.locator('#modalContent').innerText(), /Соль по вкусу/);
    await page.locator('#dEdit').click();
    await page.locator('#servings').fill('4');
    await page.locator('#recipeForm button[type=submit]').click();
    await page.waitForFunction(() => !document.querySelector('#recipeForm'));
    await page.locator('.recipe-card').click();
    await page.locator('#detailServings').fill('6');
    assert.match(await page.locator('#detailIngredients').innerText(), /750 г/);
    await page.locator('#dCook').click();
    await page.locator('[data-ingredient="0"]').check();
    await page.locator('#cookNext').click();
    assert.equal(await page.locator('.cook-step').innerText(), 'Варить');
    assert.equal(await page.locator('[data-ingredient="0"]').isChecked(), true);
    await page.locator('#cookExit').click();
    await page.locator('#dShop').click();
    await page.locator('#dClose').click();
    await page.locator('.kitchen-toolbar [data-extra-action=shopping]').click();
    await page.locator('[data-purchase="0"]').check();
    await page.locator('#closeShopping').click();
    await page.reload(); await page.waitForFunction(() => typeof db !== 'undefined' && db);
    await page.locator('.kitchen-toolbar [data-extra-action=shopping]').click();
    assert.equal(await page.locator('[data-purchase="0"]').isChecked(), true);
    await page.locator('#shoppingRecipes input[type=checkbox]').check();
    await page.locator('#buildShopping').click();
    await page.waitForFunction(() => document.querySelectorAll('#shoppingItems input').length === 3);
    await page.locator('#closeShopping').click();
    await page.locator('#addBtn').click();
    await page.locator('#title').fill('Черновик пирога');
    await page.locator('.ingredient-name').fill('Мука');
    await page.locator('.ingredient-amount').fill('1/');
    await eventually(() => page.evaluate(async () => (await metaGet('draft'))?.value?.ingredientItems?.[0]?.amount), value => value === '1/');
    await page.reload();
    await page.locator('#draftBanner button').click();
    await page.locator('#dlgActions button').filter({ hasText: 'Восстановить' }).click();
    assert.equal(await page.locator('#title').inputValue(), 'Черновик пирога');
    assert.equal(await page.locator('.ingredient-amount').inputValue(), '1/');
    await page.locator('.ingredient-amount').fill('0,5');
    await page.locator('.ingredient-unit').fill('кг');
    await page.locator('#recipeForm button[type=submit]').click();
    await page.waitForFunction(() => document.querySelectorAll('.recipe-card').length === 2);
    assert.equal(await page.evaluate(async () => !!(await metaGet('draft'))), false);
    await page.locator('.recipe-card').filter({ hasText: 'Старый борщ' }).click();
    await page.locator('#dDelete').click();
    await page.locator('#dlgActions button').filter({ hasText: /^Удалить$/ }).click();
    await page.waitForFunction(() => document.querySelectorAll('.recipe-card').length === 1);
    await page.locator('.kitchen-toolbar [data-extra-action=trash]').click();
    await page.locator('[data-restore]').click();
    await page.waitForFunction(() => document.querySelectorAll('.recipe-card').length === 2);
    await page.locator('#closeTrash').click();
    // Share uses native API, with the same text as clipboard fallback.
    await page.evaluate(() => { Object.defineProperty(navigator, 'share', { configurable: true, value: async data => { window.sharedRecipe = data; } }); });
    await page.locator('.recipe-card').filter({ hasText: 'Старый борщ' }).click();
    await page.locator('#dShare').click();
    assert.match(await page.evaluate(() => window.sharedRecipe.text), /Старый борщ/);
    await page.locator('#dClose').click();
    await page.evaluate(async () => { const r = (await dbGetAll()).find(r => r.title === 'Черновик пирога'); await dbPut({ ...r, deletedAt: Date.now() }); await refresh(); });
    await page.locator('.kitchen-toolbar [data-extra-action=backup]').click();
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#dlgActions button').filter({ hasText: 'Скачать JSON' }).click();
    const download = await downloadPromise;
    const fs = require('node:fs');
    const backup = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
    assert.equal(backup.version, 2); assert.equal(backup.recipes.length, 2); assert.equal(backup.shopping.length, 3);
    assert.equal(backup.recipes.find(r => r.title === 'Старый борщ').favorite, true);
    assert.ok(backup.recipes.find(r => r.title === 'Черновик пирога').deletedAt);
    const restoreContext = await browser.newContext({ viewport: { width: 320, height: 700 } });
    const restored = await restoreContext.newPage();
    restored.on('pageerror', e => errors.push(e.message));
    await restored.goto('http://127.0.0.1:8000/');
    await restored.waitForFunction(() => typeof db !== 'undefined' && db);
    await restored.locator('#importFile').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
    await eventually(() => restored.evaluate(async () => (await dbGetAllRaw()).length), n => n === 2);
    assert.equal(await restored.evaluate(async () => (await dbGetAll()).length), 1);
    assert.equal(await restored.evaluate(async () => (await metaGet('shopping')).value.length), 3);
    await restored.locator('#importFile').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
    await eventually(() => restored.locator('#toast').innerText(), s => s.includes('пропущено: 2'));
    assert.equal(await restored.evaluate(async () => (await dbGetAllRaw()).length), 2);
    await restored.locator('.kitchen-toolbar [data-extra-action=trash]').click();
    await restored.locator('[data-purge]').click();
    await restored.locator('#dlgActions button').filter({ hasText: 'Удалить навсегда' }).click();
    await eventually(() => restored.evaluate(async () => (await dbGetAllRaw()).length), n => n === 1);
    await restored.locator('#closeTrash').click();
    // Legacy v1 imports remain compatible and text is not interpreted as HTML.
    const legacy = { app: 'recipes98', version: 1, recipes: [{ title: '<img src=x onerror=alert(1)>', ingredients: 'Яйцо — 2 шт', createdAt: 123 }] };
    await restored.locator('#importFile').setInputFiles({ name: 'old.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(legacy)) });
    await eventually(() => restored.evaluate(async () => (await dbGetAll()).length), n => n === 2);
    assert.equal(await restored.locator('.recipe-card h3 img').count(), 0);
    await restored.locator('.recipe-card').filter({ hasText: 'Старый борщ' }).click();
    await restored.locator('#dEdit').click();
    assert.equal(await restored.evaluate(() => document.querySelector('#modalContent').scrollWidth <= document.querySelector('#modalContent').clientWidth + 2), true);
    await restored.locator('#title').fill('Черновик с фото');
    await restored.locator('#imageGal').setInputFiles(require('node:path').join(__dirname, '../icons/icon-192.png'));
    await eventually(() => restored.evaluate(async () => (await metaGet('draft'))?.value?.image?.size), n => n > 0);
    await restored.reload(); await restored.locator('#draftBanner button').click();
    await restored.locator('#dlgActions button').filter({ hasText: 'Восстановить' }).click();
    await restored.locator('#imagePreview').waitFor({ state: 'visible' });
    assert.equal(await restored.locator('#imagePreview').isVisible(), true);
    await restoreContext.close();
    await eventually(() => page.evaluate(async () => !!(await metaGet('backup'))));
    await page.evaluate(() => metaPut('backup', { exportedAt: Date.now() - 8 * 86400000 }));
    await page.reload(); await page.locator('#backupBanner:not(.hidden)').waitFor();
    await page.locator('.kitchen-toolbar [data-extra-action=shopping]').click();
    assert.equal(await page.evaluate(() => document.querySelector('#modalSheet').scrollWidth <= document.querySelector('#modalSheet').clientWidth + 2), true);
    await page.screenshot({ path: '/tmp/recipe-shopping.png' });
    await page.locator('#closeShopping').click();
    await page.evaluate(() => navigator.serviceWorker.ready.then(() => new Promise(resolve => navigator.serviceWorker.controller ? resolve() : navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true }))));
    await context.setOffline(true);
    await page.reload(); await page.locator('.recipe-card').first().waitFor();
    await page.locator('.recipe-card').filter({ hasText: 'Старый борщ' }).click();
    await page.locator('#dCook').click(); await page.locator('.cook-step').waitFor();
    assert.deepEqual(errors, []);
    console.log('PASS: migration, legacy editing, portions, cooking, shopping persistence, drafts, trash restore, share, backup, reminder, v1/v2 import, deduplication including trash, permanent deletion, photo drafts, narrow mobile layout, offline');
  } finally { if (browser) await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(e => { console.error(e); process.exitCode = 1; });
